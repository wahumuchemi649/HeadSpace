/**
 * Format any raw phone input with a selected country dial code.
 * - If the raw input already starts with '+', keep it and clean whitespace.
 * - Otherwise, strips any national trunk zero (e.g. 0712345678 -> 712345678)
 *   and prefixes with the provided country code (e.g. +254712345678).
 */
export function formatInternationalPhone(countryCode = '+254', rawPhone = '') {
  if (!rawPhone) return '';
  const trimmed = String(rawPhone).trim();
  if (trimmed.startsWith('+')) {
    return trimmed.replace(/\s+/g, '');
  }
  const cleanDigits = trimmed.replace(/\D/g, '');
  const codeDigits = String(countryCode).replace('+', '');

  // If user already typed the dial code without plus e.g. 254712345678
  if (cleanDigits.startsWith(codeDigits)) {
    return `+${cleanDigits}`;
  }

  // Strip leading national trunk zeros
  const stripped = trimmed.replace(/^0+/, '').replace(/\s+/g, '');
  return `${countryCode || '+254'}${stripped}`;
}

/**
 * Extracts digits only, formatted for numeric or backend storage.
 */
export function formatDigitsPhone(countryCode = '+254', rawPhone = '') {
  const international = formatInternationalPhone(countryCode, rawPhone);
  return international.replace(/\D/g, '');
}
